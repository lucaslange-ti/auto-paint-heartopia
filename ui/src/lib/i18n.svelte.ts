const dicts: Record<string, Dict> = { 'pt-BR': ptBR, 'en-US': enUS };

class I18n {
  lang = $state('pt-BR');

  set(lang: string) {
    this.lang = dicts[lang] ? lang : 'pt-BR';
  }

  t = (key: string, vars?: Record<string, string | number>): string => {
    const d = dicts[this.lang] ?? ptBR;
    let s = d[key] ?? ptBR[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };

  get languages() {
    return Object.keys(dicts);
  }
}

export const i18n = new I18n();
export const t = i18n.t;
